# Pruebas del visor (v39.43): pestaña ▾ de la barra oculta a la izquierda, al centro o a la derecha; candado del tamaño en página a página
# (no deja cambiar el zoom y, al pasar, se quedan el tamaño y la zona; en pantalla completa, botón en una esquina casi transparente);
# y doble página de una en una (la de la derecha pasa a la izquierda) o de dos en dos.
import sys, json, os, pathlib, subprocess, time
from playwright.sync_api import sync_playwright
folder = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '.').resolve()
n = fail = 0
def eq(name, got, want):
    global n, fail
    n += 1
    if got != want: fail += 1; print('FALLA', name, '\n  got :', json.dumps(got, ensure_ascii=False), '\n  want:', json.dumps(want, ensure_ascii=False))
PAPER = "(id, t, o = {}) => NEWF({id, title: t, authors: ['Pérez, Juan'], year: 2024, venue: '', type: 'articulo', doi: '', url: '', accessed: '', general: '', tagIds: [], notes: [], cites: {}, related: [], refTo: [], reading: 'por_leer', rating: 0, sectionIds: [], created: '2026-01-01T00:00:00.000Z', ...o})"
FILE = """(async () => { const L = await vwPdfLib(), d = await L.PDFDocument.create(), f = await d.embedFont(L.StandardFonts.Helvetica);
  for (let i = 0; i < 8; i++) { const p = d.addPage([595, 842]); for (let y = 780; y > 60; y -= 24) p.drawText(`Pagina ${i + 1} linea ${y}`, {x: 60, y, size: 12, font: f}); }
  return new File([await d.save()], 'ocho.pdf', {type: 'application/pdf'}); })()"""
PORT = 8802
VIS = "[...document.querySelectorAll('#vw .vwp')].filter(p => p.offsetParent).map(p => +p.dataset.i)"
with sync_playwright() as pw:
    kw = {'executable_path': '/opt/pw-browsers/chromium'} if os.path.exists('/opt/pw-browsers/chromium') else {}
    b = pw.chromium.launch(**kw); errs = []
    srv = subprocess.Popen([sys.executable, '-I', '-m', 'http.server', str(PORT), '-d', str(folder)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
    def device(mobile=False):
        c = b.new_context(**pw.devices['Pixel 7'], service_workers='block') if mobile else b.new_context(viewport={'width': 1280, 'height': 800}, service_workers='block')
        p = c.new_page(); p.on('pageerror', lambda e: errs.append(str(e))); p.add_init_script("window.ASK_AUTO = 'accept'")
        p.goto(f'http://localhost:{PORT}/index.html'); p.wait_for_timeout(1000); p.evaluate(f"window.P = {PAPER}; 0")
        p.evaluate(f"(async () => {{ db.settings.pdfTab = 'app'; db.papers.length = 0; db.papers.push(P('p1', 'Paper con PDF', {{pdf: {{name: 'prueba.pdf'}}}})); PDF_FILES.set('p1', await {FILE}); markDirty(); render(); }})()")
        p.evaluate("pdfOpen('p1', 1)"); p.wait_for_timeout(1800); return c, p
    cA, A = device()
    N = A.evaluate("VW.pages.length")
    eq('el PDF de prueba tiene 8 páginas', N, 8)
    # ---- pestaña ▾ de la barra oculta
    A.click('#vwMoreB'); A.wait_for_timeout(150); A.click("#vwMenu button[data-onclick=\"vwCfgMenu()\"]"); A.wait_for_timeout(150)
    eq('⚙ Ajustes del visor tiene la pestaña de la barra (izquierda, centro, derecha)', A.evaluate("['pestaña ▾', 'A la izquierda', 'En el centro', 'A la derecha'].map(t => $('#vwMenu').textContent.includes(t))"), [True] * 4)
    eq('por defecto, en el centro', A.evaluate("VW.tbPos"), 'c')
    A.click("#vwMenu button[data-onclick=\"vwTabPos('r');vwCfgMenu()\"]"); A.wait_for_timeout(150)
    eq('elegir no cierra el menú y marca la opción', A.evaluate("[!$('#vwMenu').hidden, [...$('#vwMenu').querySelectorAll('button')].find(b => b.textContent.includes('A la derecha')).textContent.trim().startsWith('✓')]"), [True, True])
    eq('se recuerda en el dispositivo', A.evaluate("JSON.parse(localStorage.getItem('gp-vw-read')).tab"), 'r')
    A.evaluate("$('#vwMenu').hidden = true; vwFs(true); vwTbHide(true)"); A.wait_for_timeout(300)
    tab = A.evaluate("(() => { const r = $('#vwTbTab').getBoundingClientRect(), D = $('#vw').getBoundingClientRect(); return [Math.round(D.right - r.right), Math.round(r.top - D.top)]; })()")
    eq('a la derecha: pegada al borde derecho, arriba', [0 <= tab[0] <= 20, tab[1] <= 2], [True, True])
    A.evaluate("vwTabPos('l')"); A.wait_for_timeout(100)
    tab = A.evaluate("(() => { const r = $('#vwTbTab').getBoundingClientRect(), D = $('#vw').getBoundingClientRect(); return Math.round(r.left - D.left); })()")
    eq('a la izquierda: pegada al borde izquierdo', 0 <= tab <= 20, True)
    A.evaluate("vwTabPos('c')"); A.wait_for_timeout(100)
    tab = A.evaluate("(() => { const r = $('#vwTbTab').getBoundingClientRect(), D = $('#vw').getBoundingClientRect(); return Math.round((r.left + r.right) / 2 - (D.left + D.right) / 2); })()")
    eq('en el centro, como antes', abs(tab) <= 2, True)
    eq('sin página a página no hay candado en la esquina', A.evaluate("getComputedStyle($('#vwLock')).display"), 'none')
    A.evaluate("vwFs(false)"); A.wait_for_timeout(300)
    # ---- candado del tamaño (página a página)
    eq('sin página a página el candado no se puede poner', A.evaluate("vwLockSet(true); VW.zLock || false"), False)
    eq('el botón 🔓 de la barra solo se ve en página a página', A.evaluate("getComputedStyle(document.querySelector('#vw .vwh .vwlk')).display"), 'none')
    A.evaluate("vwRdSet('flip', 1); vwGo(0, true)"); A.wait_for_timeout(500)
    eq('en página a página se ve el 🔓 de la barra', A.evaluate("(b => [getComputedStyle(b).display !== 'none', b.textContent])(document.querySelector('#vw .vwh .vwlk'))"), [True, '🔓'])
    A.evaluate("vwReadMenu()"); A.wait_for_timeout(100)
    eq('el submenú ofrece el candado (K)', A.evaluate("$('#vwMenu').textContent.includes('Candado del tamaño')"), True)
    A.evaluate("$('#vwMenu').hidden = true; vwZoomBy(1.6)"); A.wait_for_timeout(400)
    A.evaluate("(() => { const s = $('#vwScroll'); s.scrollTop = 200; })()"); A.wait_for_timeout(150)
    pos0 = A.evaluate("[VW.scale, $('#vwScroll').scrollLeft, $('#vwScroll').scrollTop]")
    eq('acercado: hay zona que mover', pos0[2], 200)
    A.click('#vw .vwh .vwlk'); A.wait_for_timeout(150)
    eq('el botón pone el candado (🔒, pulsado)', A.evaluate("[VW.zLock, document.querySelector('#vw .vwh .vwlk').textContent, document.querySelector('#vw .vwh .vwlk').getAttribute('aria-pressed'), $('#vw').classList.contains('zlock')]"), [True, '🔒', 'true', True])
