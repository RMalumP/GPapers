    A.evaluate("vwTabPos('l')"); A.wait_for_timeout(100)
    eq('con la pestaña a la izquierda, el candado se va a la derecha', A.evaluate("(() => { const r = $('#vwLock').getBoundingClientRect(), D = $('#vw').getBoundingClientRect(); return D.right - r.right <= 20; })()"), True)
    A.evaluate("vwTabPos('c')")
    A.click('#vwLock'); A.wait_for_timeout(150)
