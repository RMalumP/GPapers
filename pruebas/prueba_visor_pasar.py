    eq('← vuelve igual', A.evaluate("[VW.cur, VW.scale, $('#vwScroll').scrollTop]"), [0, pos0[0], pos0[2]])
    A.keyboard.press('PageDown'); A.wait_for_timeout(300)
    eq('AvPág pasa de página sin mover la hoja (v39.46)', A.evaluate("[VW.cur, $('#vwScroll').scrollTop, VW.scale]"), [1, pos0[2], pos0[0]])
    A.keyboard.press('ArrowDown'); A.wait_for_timeout(300); A.keyboard.press('ArrowUp'); A.wait_for_timeout(300)
    eq('↓ y ↑ también solo pasan de página', A.evaluate("[VW.cur, $('#vwScroll').scrollTop]"), [1, pos0[2]])
    A.mouse.move(600, 400); A.mouse.wheel(0, 400); A.mouse.wheel(150, 0); A.wait_for_timeout(300)
    eq('con el candado la rueda no mueve la hoja', A.evaluate("[$('#vwScroll').scrollLeft, $('#vwScroll').scrollTop]"), [pos0[1], pos0[2]])
    A.evaluate("""(() => { const T = (x, y) => [{clientX: x, clientY: y}, {clientX: x + 100, clientY: y}], ev = (type, t) => ({type, touches: t, preventDefault() {}});
      vwTouch(ev('touchstart', T(300, 300))); vwTouch(ev('touchmove', T(250, 200))); vwTouch(ev('touchmove', T(200, 100))); vwTouch(ev('touchend', [])); })()"""); A.wait_for_timeout(200)
    eq('ni arrastrando con dos dedos', A.evaluate("[$('#vwScroll').scrollLeft, $('#vwScroll').scrollTop, VW.scale]"), [pos0[1], pos0[2], pos0[0]])
    eq('ni con el dedo (la página no se desplaza)', A.evaluate("getComputedStyle($('#vwScroll')).touchAction"), 'none')
    A.set_viewport_size({'width': 1100, 'height': 760}); A.wait_for_timeout(400)
    eq('cambiar el tamaño de la ventana no reajusta el zoom', A.evaluate("VW.scale") == pos0[0], True)
    A.set_viewport_size({'width': 1280, 'height': 800}); A.wait_for_timeout(300)
    eq('el menú lo dice', A.evaluate("vwRdSum().includes('🔒')"), True)
    # pantalla completa: botón en la esquina, casi transparente
    A.evaluate("vwFs(true)"); A.wait_for_timeout(300)
    lk = A.evaluate("(() => { const b = $('#vwLock'), r = b.getBoundingClientRect(), D = $('#vw').getBoundingClientRect(), cs = getComputedStyle(b); return [cs.display, +cs.opacity, Math.round(r.left - D.left), Math.round(D.bottom - r.bottom), b.textContent]; })()")
